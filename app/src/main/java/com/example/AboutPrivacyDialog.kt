@Composable
fun AboutPrivacyDialog(
    onDismissRequest: () -> Unit
) {
    Dialog(onDismissRequest = onDismissRequest) {
        Surface(
            modifier = Modifier
                .fillMaxWidth()
                .clip(RoundedCornerShape(24.dp))
                .testTag("about_privacy_dialog"),
            color = MaterialTheme.colorScheme.surface,
            tonalElevation = 6.dp
        ) {
            Column(
                modifier = Modifier
                    .padding(24.dp)
                    .verticalScroll(rememberScrollState())
            ) {
                // Header Row
                Row(
                    modifier = Modifier.fillMaxWidth(),
                    verticalAlignment = Alignment.CenterVertically,
                    horizontalArrangement = Arrangement.SpaceBetween
                ) {
                    Row(verticalAlignment = Alignment.CenterVertically) {
                        Box(
                            modifier = Modifier
                                .size(40.dp)
                                .clip(CircleShape)
                                .background(MaterialTheme.colorScheme.primaryContainer),
                            contentAlignment = Alignment.Center
                        ) {
                            Icon(
                                imageVector = Icons.Default.Shield,
                                contentDescription = "Security Shield",
                                tint = MaterialTheme.colorScheme.primary,
                                modifier = Modifier.size(24.dp)
                            )
                        }
                        Spacer(modifier = Modifier.width(12.dp))
                        Column {
                            Text(
                                text = "Sunflower",
                                style = MaterialTheme.typography.titleMedium,
                                fontWeight = FontWeight.Bold,
                                color = MaterialTheme.colorScheme.onSurface
                            )
                            Text(
                                text = "WhatsApp Web Companion",
                                style = MaterialTheme.typography.bodySmall,
                                color = MaterialTheme.colorScheme.onSurfaceVariant
                            )
                        }
                    }

                    IconButton(
                        onClick = onDismissRequest,
                        modifier = Modifier.testTag("close_about_dialog_button")
                    ) {
                        Icon(
                            imageVector = Icons.Default.Close,
                            contentDescription = "Close Dialog",
                            tint = MaterialTheme.colorScheme.onSurfaceVariant
                        )
                    }
                }

                Spacer(modifier = Modifier.height(16.dp))
                HorizontalDivider(color = MaterialTheme.colorScheme.surfaceVariant)
                Spacer(modifier = Modifier.height(16.dp))

                // Section: Independent Companion Notice
                PrivacySectionCard(
                    icon = Icons.Default.Info,
                    title = "Independent Companion Notice",
                    description = "This application is an independent wrapper created to access the official WhatsApp Web service in a mobile-friendly view. It is NOT affiliated with, sponsored by, or endorsed by WhatsApp LLC or Meta Platforms, Inc."
                )

                Spacer(modifier = Modifier.height(12.dp))

                // Section: Privacy & Security
                PrivacySectionCard(
                    icon = Icons.Default.Lock,
                    title = "Zero Interception & Privacy",
                    description = "All communications occur directly between your device and WhatsApp's official servers (https://web.whatsapp.com/) over strict HTTPS. This app does NOT collect, store, transmit, or read your messages, contacts, cookies, or credentials. Everything remains inside WhatsApp's sandboxed web container."
                )

                Spacer(modifier = Modifier.height(12.dp))

                // Section: How to Link Devices
                PrivacySectionCard(
                    icon = Icons.Default.QrCode,
                    title = "How Device Linking Works",
                    description = "1. Open WhatsApp on your primary phone.\n2. Tap Menu (or Settings) > Linked Devices.\n3. Tap 'Link a Device'.\n4. Point your camera at the QR code displayed on this screen to authenticate."
